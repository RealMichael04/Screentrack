import "server-only";
import { ApiError } from "./apiError.js";
import { addDays, isValidDate } from "./calendar.js";
import { getDb } from "./db.js";
import { discoverUpcomingMovies, getFranchise, getMovie, getSeasonEpisodes, getTvShow } from "./tmdb.js";

const MAX_SHOWS = 40;
const MAX_FRANCHISES = 15;
const MAX_POPULAR = 15;
const MAX_MOVIE_REFRESH = 40;

function monthRange(month) {
  if (typeof month !== "string" || !/^\d{4}-\d{2}$/.test(month) || !isValidDate(`${month}-01`)) {
    throw new ApiError(400, "That month isn't valid.");
  }
  const first = `${month}-01`;
  const [year, monthNumber] = month.split("-").map(Number);
  // Day 0 of the next month is the last day of this one.
  const last = new Date(Date.UTC(year, monthNumber, 0)).toISOString().slice(0, 10);
  return { first, last };
}

const settled = async (promises) =>
  (await Promise.allSettled(promises)).filter((r) => r.status === "fulfilled").map((r) => r.value);

/** Which seasons could have episodes airing inside the month. */
function seasonsOverlapping(seasons, first, last) {
  const dated = seasons.filter((s) => s.airDate).sort((a, b) => a.airDate.localeCompare(b.airDate));
  return dated.filter((season, i) => {
    const next = dated[i + 1];
    return season.airDate <= last && (!next || next.airDate >= first);
  });
}

function classifyEpisode(episode) {
  if (episode.episodeType === "finale") return "finale";
  if (episode.episodeNumber === 1) return episode.seasonNumber === 1 ? "premiere" : "season";
  return "episode";
}

function episodeSubtitle(episode, type) {
  if (type === "premiere") return "Series premiere";
  if (type === "season") return `Season ${episode.seasonNumber} premiere`;
  if (type === "finale") return `Season ${episode.seasonNumber} finale`;
  return `S${episode.seasonNumber} E${episode.episodeNumber} · ${episode.title}`;
}

async function showEvents(show, first, last) {
  const details = await getTvShow(show.tmdb_id);
  const seasons = seasonsOverlapping(details.seasons, first, last);
  const lists = await settled(seasons.map((s) => getSeasonEpisodes(show.tmdb_id, s.seasonNumber)));
  return lists
    .flat()
    .filter((e) => e.releaseDate && e.releaseDate >= first && e.releaseDate <= last)
    .map((e) => {
      const type = classifyEpisode(e);
      return {
        id: `tv-${show.tmdb_id}-${e.seasonNumber}-${e.episodeNumber}`,
        date: e.releaseDate,
        type,
        title: show.title,
        subtitle: episodeSubtitle(e, type),
        posterUrl: show.poster_url,
        href: `/track/tv/${show.tmdb_id}`,
      };
    });
}

/**
 * Everything happening in a month for this person. Dates come from TMDB and
 * from their own schedules. Nothing here is generated by AI.
 */
export async function getMonthEvents(userId, month) {
  const { first, last } = monthRange(month);
  const today = new Date().toISOString().slice(0, 10);
  const sql = getDb();

  const [tracked, scheduleCollections, planned] = await Promise.all([
    sql`
      select media_type, tmdb_id, title, poster_url, release_date::text, collection_id
      from tracked_titles
      where user_id = ${userId}
      order by updated_at desc
    `,
    sql`select distinct tmdb_id from schedules where user_id = ${userId} and media_type = 'collection'`,
    sql`
      select s.id, s.title, i.scheduled_date::text as date, count(*)::int as items, sum(i.runtime_minutes)::int as minutes
      from schedule_items i
      join schedules s on s.id = i.schedule_id
      where s.user_id = ${userId} and i.watched_at is null
        and i.scheduled_date >= ${first}::date and i.scheduled_date <= ${last}::date
      group by s.id, s.title, i.scheduled_date
    `,
  ]);

  const movies = tracked.filter((t) => t.media_type === "movie");
  const shows = tracked.filter((t) => t.media_type === "tv").slice(0, MAX_SHOWS);

  // Release dates can move, so anything not yet out is looked up fresh.
  const unreleased = movies.filter((m) => !m.release_date || m.release_date >= today).slice(0, MAX_MOVIE_REFRESH);
  const refreshed = new Map(
    (await settled(unreleased.map((m) => getMovie(m.tmdb_id)))).map((m) => [m.tmdbId, m.releaseDate])
  );

  const events = [];
  const movieKeys = new Set();

  for (const movie of movies) {
    const date = refreshed.has(movie.tmdb_id) ? refreshed.get(movie.tmdb_id) : movie.release_date;
    if (date && date >= first && date <= last) {
      movieKeys.add(movie.tmdb_id);
      events.push({
        id: `movie-${movie.tmdb_id}`,
        date,
        type: "movie",
        title: movie.title,
        subtitle: "Movie release",
        posterUrl: movie.poster_url,
        href: `/track/movie/${movie.tmdb_id}`,
      });
    }
  }

  const collectionIds = [
    ...new Set([...movies.map((m) => m.collection_id).filter(Boolean), ...scheduleCollections.map((s) => s.tmdb_id)]),
  ].slice(0, MAX_FRANCHISES);

  const [showResults, franchises, popular] = await Promise.all([
    settled(shows.map((show) => showEvents(show, first, last))),
    settled(collectionIds.map((id) => getFranchise(id))),
    discoverUpcomingMovies(first, last).catch(() => []),
  ]);
  events.push(...showResults.flat());

  for (const franchise of franchises) {
    for (const movie of franchise.movies) {
      if (movie.releaseDate && movie.releaseDate >= first && movie.releaseDate <= last && !movieKeys.has(movie.tmdbId)) {
        movieKeys.add(movie.tmdbId);
        events.push({
          id: `movie-${movie.tmdbId}`,
          date: movie.releaseDate,
          type: "movie",
          title: movie.title,
          subtitle: `From ${franchise.title}`,
          posterUrl: movie.posterUrl,
          href: null,
        });
      }
    }
  }

  for (const movie of popular.slice(0, MAX_POPULAR)) {
    if (movie.releaseDate && !movieKeys.has(movie.tmdbId)) {
      movieKeys.add(movie.tmdbId);
      events.push({
        id: `popular-${movie.tmdbId}`,
        date: movie.releaseDate,
        type: "popular",
        title: movie.title,
        subtitle: "Popular release",
        posterUrl: movie.posterUrl,
        href: null,
        addable: { mediaType: "movie", tmdbId: movie.tmdbId },
      });
    }
  }

  for (const row of planned) {
    events.push({
      id: `plan-${row.id}-${row.date}`,
      date: row.date,
      type: "plan",
      title: row.title,
      subtitle: `Your schedule · ${row.items} to watch`,
      posterUrl: null,
      href: `/schedule/${row.id}`,
    });
  }

  events.sort((a, b) => a.date.localeCompare(b.date) || a.title.localeCompare(b.title));
  return { month, first, last, nextMonthStart: addDays(last, 1), followingCount: tracked.length, events };
}
